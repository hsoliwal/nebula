"""Deterministic, read-only 68-concept Nebula/SWT/RWT route projection."""
import argparse
import csv
from io import StringIO
from pathlib import Path
import sys

REPO = Path(__file__).resolve().parents[3]
NATIVE = REPO / "docs/m3/custom-widgets/WIDGET_MATRIX.tsv"
RWT = REPO / "docs/m3/rwt/RWT_COLUMN.tsv"
OUTPUT = REPO / "m3/web-widget-reverse/WEB_SWT_CONCEPT_MAP.tsv"
HEADER = (
    "rank", "concept_id", "concept", "swt_stock", "nebula_class",
    "rwt_class", "rwt_route", "rwt_only_status", "primary_rwt_errors",
    "primary_missing_symbols", "decision", "proof_status"
)
ROUTES = {
    "RAP_NATIVE": "EXISTING_RAP_API",
    "CANVAS_GC_REPLAY": "ORIGINAL_CANVAS_GC_GATE",
    "REBUILD_AS_PAINTER": "ORIGINAL_COMPOSITE_PAINTER_GATE",
    "BLOCKED(draw2d absent on RWT)": "BLOCKED_KEEP_ORIGINAL",
    "BLOCKED(org.eclipse.swt.printing absent in RWT)": "BLOCKED_KEEP_ORIGINAL"
}


def load(path):
    with path.open(encoding="utf-8", newline="") as stream:
        reader = csv.DictReader(stream, delimiter="\t")
        if not reader.fieldnames:
            raise ValueError("missing TSV header: " + str(path))
        data = list(reader)
    if not data or any(None in row.values() for row in data):
        raise ValueError("incomplete TSV: " + str(path))
    ids = [item["concept_id"] for item in data]
    if not all(ids) or len(ids) != len(set(ids)):
        raise ValueError("duplicate/blank concept_id: " + str(path))
    return data


def build(native, rwt):
    n = {row["concept_id"]: row for row in native}
    r = {row["concept_id"]: row for row in rwt}
    if len(n) != len(native) or len(r) != len(rwt):
        raise ValueError("duplicate concepts")
    if not set(n).issubset(r):
        raise ValueError("native concept is missing in RWT")
    ranks = [int(row["rank"]) for row in rwt]
    if len(ranks) != len(set(ranks)):
        raise ValueError("duplicate RWT rank")
    if any(row["rwt_route"] not in ROUTES for row in rwt):
        raise ValueError("unknown RWT rendering route")
    sink = StringIO()
    writer = csv.writer(sink, delimiter="\t", lineterminator="\n")
    writer.writerow(HEADER)
    for row in sorted(rwt, key=lambda item: int(item["rank"])):
        local = n.get(row["concept_id"])
        writer.writerow((
            row["rank"],
            row["concept_id"],
            row["concept"],
            local["swt_stock"] if local else "-",
            local["nebula_class"] if local else row["nebula_primary"],
            row["rwt_class"],
            row["rwt_route"],
            "NATIVE_CATALOGUED" if local else "RWT_ONLY_HOLD",
            row["primary_bundle_rwt_errors"],
            row["primary_missing_symbols"],
            ROUTES[row["rwt_route"]],
            "HOLD_UNQUALIFIED"))
    return sink.getvalue()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true",
                        help="compare generated bytes with committed map; never write")
    args = parser.parse_args()
    try:
        current = build(load(NATIVE), load(RWT))
        if args.check:
            with OUTPUT.open(encoding="utf-8", newline="") as stream:
                committed = stream.read()
            if committed != current:
                raise ValueError("WEB_SWT_CONCEPT_MAP.tsv stale or altered")
            print("PASS full concept map source parity (" +
                  str(current.count("\n") - 1) + " RWT concepts)")
        else:
            sys.stdout.write(current)
        return 0
    except (ValueError, OSError, KeyError) as failure:
        print("FAIL full concept map: " + str(failure), file=sys.stderr)
        return 1


if __name__ == "__main__":
    sys.exit(main())
